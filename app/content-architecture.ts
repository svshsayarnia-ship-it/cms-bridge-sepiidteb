export function getGuide(slug: string): GuidePage | undefined {
  return guides.find((guide) => guide.slug === slug);
}

export function getConcern(slug: string): ConcernPage | undefined {
  return concerns.find((concern) => concern.slug === slug);
}

export function getBrandPage(slug: string): BrandPage | undefined {
  return brandPages.find((brand) => brand.slug === slug);
}

export function getBrandPageForLabel(label: string): BrandPage | undefined {
  const normalized = label.trim().toLocaleLowerCase("en");

  return brandPages.find((brand) =>
    brand.matchers.some(
      (matcher) => matcher.toLocaleLowerCase("en") === normalized,
    ),
  );
}

export function getGuideForArticle(slug: string): GuidePage | undefined {
  return guides.find((guide) => guide.articleSlugs.includes(slug));
}
